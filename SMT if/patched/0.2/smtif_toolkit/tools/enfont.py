LOWER['.'] = [".", ".", ".", ".", ".", ".", ".", "#", ".", "."]

SPACE_W = 2  # transparent columns for a space (plus the renderer's 1px gap)


def glyph_rows(ch):
    """Return 12 rows (strings) for a character on the full cell."""
    if ch == ' ':
        return ['.' * SPACE_W] * 12
    if ch in CAPS:
        rows = CAPS[ch]
        w = len(rows[0])
        full = ['.' * w] * 2 + rows + ['.' * w] * (10 - len(rows))
        return full[:12]
    if ch in LOWER:
        rows = LOWER[ch]
        w = max(len(r) for r in rows)
        return ['.' * w] * 2 + [r.ljust(w, '.') for r in rows]
    raise KeyError(f'no glyph for {ch!r}')


def width(ch):
    return len(glyph_rows(ch)[0])


CHARSET = set(CAPS) | set(LOWER) | {' '}


def render_tile(text, ink=2):
    """Render a tile (1+ chars, 1px gaps) to a 12x16 pixel array (3 = transparent). Returns (px, W)."""
    px = [[3] * 16 for _ in range(12)]
    x = 0
    for k, ch in enumerate(text):
        rows = glyph_rows(ch)
        w = len(rows[0])
        for y in range(12):
            for dx, c in enumerate(rows[y]):
                if c == '#':
                    px[y][x + dx] = ink
        x += w + 1
    W = x - 1
    return px, W


def tile_width(text):
    return sum(width(c) for c in text) + len(text) - 1
